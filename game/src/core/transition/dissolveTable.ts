/**
 * TABLA DE ORDEN del page-dissolve (fn37 / helper 0x0d72) — EXTRAÍDA BYTE-A-BYTE de
 * `EGA.DRV` (addr 0x1e8c, segmento plano file=addr), por desensamblado directo del driver
 * (mismo método que la tabla de polinomios 0x254d del fizzle). Ver `re/notes/dissolve-derivation.md`.
 *
 * El dissolve es un MELT POR SCANLINES del bloque de 7 líneas centrado que pinta el 0x0d72
 * (filas 46..107 de la pantalla 320×200). Son 7 BANDAS anidadas y expansivas; cada banda
 * revela sus `count` scanlines (absolutas = `startRow + índice`) en el orden de su tabla
 * `order` (índices intra-banda + 0xff = marcador de LOTE). El algoritmo de recorrido es el
 * de `dissolve.ts` (`dissolvePass`, calcado de pass_down/pass_up del driver), verificado
 * contra el desensamblado. La mecánica de planos EGA y el reparto en 2 mitades con delay son
 * artefactos de hardware/tiempo (cadencia Clase-C); en canvas basta el ORDEN de scanlines.
 */

/** Una banda del dissolve: rango de scanlines + su tabla de orden intra-banda (con 0xff). */
export interface DissolveBand {
  /** Desplazamiento en el buffer fuente (acumulado de counts; irrelevante en canvas). */
  readonly srcOffset: number;
  /** Primera scanline absoluta de la banda (DS param `[0x1b27]`). */
  readonly startRow: number;
  /** Nº de scanlines de la banda (DS param `[0x1b2b]`, = índices 0..count-1). */
  readonly count: number;
  /** Tabla de orden: índices intra-banda a revelar, 0xff cierra un lote (`transition_step`). */
  readonly order: readonly number[];
}

